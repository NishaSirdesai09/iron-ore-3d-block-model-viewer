import type { Content, TDocumentDefinitions, TableCell } from "pdfmake/interfaces";
import { SEED } from "../model/grid";
import type { GroupStats, LeaseReport } from "../model/report";

const INK = "#1e232a";
const MUTED = "#56606b";
const OCHRE = "#a06c16";
const RULE = "#d0d5db";
const STAGE = ["G1 detailed", "G2 general", "G3 prospecting", "G4 reconnaissance"];

const mt = (t: number) => (t / 1e6).toFixed(1);
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const fe = (g: number) => `${g.toFixed(1)}%`;
const c2 = (c: number) => c.toFixed(2);

const align = (a: number, left: number) => (a < left ? "left" : "right");
const head = (cells: string[], left: number): TableCell[] =>
  cells.map((text, a) => ({ text, bold: true, color: MUTED, alignment: align(a, left) }));
const row = (cells: string[], left: number): TableCell[] =>
  cells.map((text, a) => ({ text, alignment: align(a, left) }));

const lines = {
  hLineWidth: (i: number) => (i === 1 ? 0.8 : 0.4),
  vLineWidth: () => 0,
  hLineColor: () => RULE,
  paddingTop: () => 3,
  paddingBottom: () => 3,
};

function table(widths: (string | number)[], header: string[], rows: string[][], left = 1): Content {
  return {
    unbreakable: true,
    table: {
      headerRows: 1,
      dontBreakRows: true,
      widths,
      body: [head(header, left), ...rows.map((r) => row(r, left))],
    },
    layout: lines,
    fontSize: 8.5,
    margin: [0, 2, 0, 10],
  };
}

const stageShares = (g: GroupStats) =>
  [1, 2, 3, 4].map((s) => (g.tonnes ? pct(g.stages[s] / g.tonnes) : "–"));

const h2 = (text: string): Content => ({ text, fontSize: 12, bold: true, margin: [0, 10, 0, 4] });
const p = (text: string | Content[], extra: object = {}): Content => ({
  text,
  fontSize: 9,
  color: INK,
  margin: [0, 0, 0, 6],
  lineHeight: 1.25,
  ...extra,
});

/** Filename for a downloaded report at a cut-off. */
export const reportFileName = (cut: number) => `Fe-resource-report-${cut}pct-Fe.pdf`;

/**
 * pdfmake document for the resource report. Shared by the in-app download button and
 * `npm run report`; only the font differs (Roboto in the browser, Helvetica in Node).
 */
export function reportDocument(r: LeaseReport, font: string): TDocumentDefinitions {
  const cut = r.cut;
  const res = r.resource;
  return {
    info: {
      title: "Fe: Ridge lease R-07 synthetic resource report",
      subject: "Illustrative output of a synthetic block model. Not a real deposit.",
    },
    pageSize: "A4",
    pageMargins: [48, 56, 48, 56],
    defaultStyle: { font, fontSize: 9, color: INK },
    footer: (page, pages) => ({
      columns: [
        {
          text: "SYNTHETIC DATA. Illustrative model output, not a mineral resource estimate.",
          color: MUTED,
          width: "*",
        },
        { text: `${page} / ${pages}`, alignment: "right", color: MUTED, width: 40 },
      ],
      fontSize: 7.5,
      margin: [48, 20, 48, 0],
    }),
    content: [
      { text: "Fe", fontSize: 26, bold: true },
      {
        text: "Ridge lease R-07: what the block model contains",
        fontSize: 14,
        margin: [0, 0, 0, 2],
      },
      {
        text: `Cut-off ${cut}% Fe · existing drilling (14 holes) · model seed ${SEED}`,
        color: MUTED,
        margin: [0, 0, 0, 10],
      },
      {
        table: {
          widths: ["*"],
          body: [
            [
              {
                stack: [
                  {
                    text: "All data in this report is synthetic.",
                    bold: true,
                    margin: [0, 0, 0, 3],
                  },
                  {
                    text:
                      "The geology, assays, drill holes, prices and costs were generated by a computer model from a fixed random seed " +
                      "to illustrate how a block model works. They do not describe any real place or deposit. This is not a mineral " +
                      "resource or reserve estimate under UNFC, JORC, NI 43-101 or any other reporting code, and must not be presented " +
                      "as the result of field work, sampling or laboratory assays.",
                    lineHeight: 1.25,
                  },
                ],
                margin: [8, 6, 8, 6],
              },
            ],
          ],
        },
        layout: {
          hLineColor: () => OCHRE,
          vLineColor: () => OCHRE,
          hLineWidth: () => 1,
          vLineWidth: () => 1,
        },
        fontSize: 9,
        margin: [0, 0, 0, 8],
      },

      h2("Summary"),
      p(
        `Above the ${cut}% Fe cut-off the model holds ${mt(res.tonnes)} million tonnes at an average estimated grade of ` +
          `${fe(res.grade)} Fe, with a tonnage-weighted mean confidence of ${c2(res.conf)}. ` +
          `${pct((res.stages[1] + res.stages[2]) / res.tonnes)} of that tonnage is at G2 or better (confidence of 0.5 or more), ` +
          `and ${pct(res.stages[4] / res.tonnes)} is G4, ground with almost no drilling nearby.`,
      ),
      table(
        ["*", 70, 70, 70, 70],
        ["Resource above cut-off", ...STAGE.map((s) => s.split(" ")[0])],
        [["Million tonnes", ...[1, 2, 3, 4].map((s) => mt(res.stages[s]))]],
      ),

      h2("1. Rock types: how much, how rich, how sure"),
      p(
        `Share is the percentage of all ${mt(r.totalRockTonnes)} Mt of rock in the model. Grade is the tonnage-weighted ` +
          `estimated iron content. Confidence (0 to 0.97) reflects distance to the nearest drill hole. Chance is the average ` +
          `probability that a cell of that rock beats ${cut}% Fe, given its grade uncertainty.`,
      ),
      table(
        ["*", 52, 46, 48, 50, 48],
        ["Rock type", "Mt", "Share", "Fe grade", "Confidence", "Chance"],
        r.byRock.map((g) => [
          g.name,
          mt(g.tonnes),
          pct(g.shareOfRock),
          fe(g.grade),
          c2(g.conf),
          g.chanceAbove == null ? "–" : pct(g.chanceAbove),
        ]),
      ),
      p("Share of each rock type's tonnes by confidence stage:", { color: MUTED }),
      table(
        ["*", 60, 60, 60, 60],
        ["Rock type", ...STAGE.map((s) => s.split(" ")[0])],
        r.byRock.map((g) => [g.name, ...stageShares(g)]),
      ),

      h2(`2. Ore above ${cut}% Fe by type of occurrence`),
      table(
        ["*", 52, 56, 48, 50, 48],
        ["Occurrence", "Mt", "Of resource", "Fe grade", "Confidence", "G2+"],
        r.byOccurrenceAboveCut.map((g) => [
          g.name,
          mt(g.tonnes),
          res.tonnes ? pct(g.tonnes / res.tonnes) : "–",
          g.tonnes ? fe(g.grade) : "–",
          g.tonnes ? c2(g.conf) : "–",
          g.tonnes ? pct((g.stages[1] + g.stages[2]) / g.tonnes) : "–",
        ]),
      ),
      p(
        `Pocket deposits are hematite bodies of fewer than 70 connected cells; larger bodies are reef ore. ` +
          `${r.floatFragments} float-ore fragments are mapped on the slopes below ore outcrops.`,
        { color: MUTED },
      ),

      // Keep each heading on the same page as its table.
      {
        unbreakable: true,
        stack: [
          h2("3. Grade and tonnage at other cut-offs"),
          table(
            ["*", 70, 70, 90],
            ["Cut-off", "Mt", "Fe grade", "Mt at G2 or better"],
            r.gradeTonnage.map((g) => [`${g.cut}% Fe`, mt(g.tonnes), fe(g.grade), mt(g.g2Plus)]),
          ),
        ],
      },

      h2("4. Drill holes"),
      table(
        [44, "*", 50, 50, 44, 140],
        ["Hole", "Type", "East", "North", "Depth", "Best intercept"],
        r.holes.map((h) => [
          h.id,
          h.kind,
          `${h.east} m`,
          `${h.north} m`,
          `${h.depth} m`,
          h.intercept,
        ]),
        2,
      ),

      h2("How the numbers are made"),
      {
        ul: [
          "Grid of 44 × 32 × 20 cells, each 25 m × 25 m × 10 m. Tonnes = volume × density (waste 2.6, BHQ 3.3, hematite 4.2, blue dust 3.2, laterite 3.0 t/m³).",
          "Hematite and blue dust are iron oxide (Fe2O3, about 70% Fe when pure). BHQ is hematite banded with quartz, so its iron content is lower. Laterite is a weathered, iron-rich surface cap.",
          "Confidence decays with horizontal distance to each hole (exp(-d²/3.3²), zero beyond 7 cells) and below the hole's bottom; the top two cells get at least 0.3 from surface mapping.",
          "Estimated grade departs further from the model's true grade where confidence is low. Uncertainty sigma = 1.5 + 11 × (1 - confidence) % Fe; chance above cut-off = normal CDF of (grade - cut-off) / sigma.",
          "Stages follow the spirit of the UNFC geological axis: G1 at confidence 0.75 or more, G2 at 0.5 or more, G3 at 0.25 or more, otherwise G4. Figures use existing drilling only.",
        ],
        fontSize: 8.5,
        lineHeight: 1.25,
      },
    ],
  };
}
